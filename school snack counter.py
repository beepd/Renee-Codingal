snack_counts = [3, 4, 2, 5]
print("\nInitial snack counts:", snack_counts)
snack_counts.append(6)
print("After adding a value:", snack_counts)
count_of_fours = snack_counts.count(4)
print("\nNumber of times '4' appears:", count_of_fours)
snack_counts.reverse()
print("Reversed snack counts:", snack_counts)
